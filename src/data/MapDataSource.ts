import type {SpatialMetricsIndex,SpatialMetricPage} from '../shared/spatialMetrics';
import type { AggregateIndex, AggregateBatchRef, AggregateRegion } from '../shared/lod4Aggregates';
import type { ParcelFilterMetadata, ParcelFilterIndex, ParcelFilterBatchRef, ParcelFilterGrid } from '../shared/parcelFilters';
import type { Lod4Index, Lod4Region } from '../shared/lod4';
import type { NeighborhoodData } from '../map/types';
import type {PreviewIndex,PreviewTileRef} from '../shared/heatmapPreview';
import type { Manifest, ParcelRecord, PackRef } from '../shared/httpPack';
import type {ChunkBounds,NeighborhoodChunk,NeighborhoodChunkRef} from '../shared/neighborhoodChunks';
import type { AnalyticsIndex, MetricId, BitmapInspection } from '../shared/mapAnalytics';
import type { LayerAnalysis } from '../shared/layerAnalysis';
import type { PatternInputs } from '../shared/patterns';
export type LoadedChunk = { x: number; y: number; size: number };
export type ParcelJob = { key: string; first: number; last: number; ids: number[]; accept?: (id:number)=>boolean; singleSizes?: Uint8Array; validatedRecords?: ParcelRecord[]; skipIds?: ReadonlySet<number>; contains?: (id: number) => boolean; pack?: PackRef; neighborhood?: number; error?: string; failure?:unknown };
export interface MapDataSource {
    readonly mode: 'static';
    setRequestContext?(context:{viewRevision?:number;modeRevision?:number;mode?:string}):void;
    onChunkPackLoaded?: (chunk: LoadedChunk) => void;
    onPreviewTileLoaded?: (chunk: LoadedChunk) => void;
    getManifest(): Promise<Pick<Manifest, 'regions' | 'snapshot' | 'publishedHeight'>&{layout?:string}>;
    getBitmapAreaData?():Promise<{maxArea:number;neighborhoodMeans:number[]}>;
    getLod4Index?(): Promise<Lod4Index | undefined>;
    getLod4Region?(index:Lod4Index,id:number,signal:AbortSignal):Promise<Lod4Region>;
    getLod4SummaryIndex?():Promise<AggregateIndex|undefined>;
    getLod4SummaryBatch?(index:AggregateIndex,ref:AggregateBatchRef,signal:AbortSignal):Promise<AggregateRegion[]>;
    getParcelFilterMetadata?():Promise<ParcelFilterMetadata>;
    getParcelFilterIndex?(low:number,high:number,signal:AbortSignal):Promise<ParcelFilterIndex>;
    getParcelFilterBatch?(index:ParcelFilterIndex,ref:ParcelFilterBatchRef,signal:AbortSignal):Promise<ParcelFilterGrid[]>;
    getSpatialMetricsIndex?():Promise<SpatialMetricsIndex>;
    getSpatialMetricPage?(region:number,signal:AbortSignal):Promise<SpatialMetricPage>;
    getLayerAnalysis?():Promise<LayerAnalysis>;
    getParcelClassBytes?(signal?:AbortSignal):Promise<Uint8Array>;
    getClassPreview?():Promise<PreviewIndex>;
    getAreaMetric?(signal?:AbortSignal):Promise<Float32Array>;
    getAnalyticsIndex?(): Promise<AnalyticsIndex>;
    getAnalyticsMetric?(id: MetricId, signal?:AbortSignal): Promise<{ values: Float32Array; preview: PreviewIndex }>;
    inspectBitmap?(id: number): Promise<BitmapInspection>;
    getPatternMatches?(pattern: number): Promise<number[]>;
    getPatternInputs?(signal:AbortSignal):Promise<PatternInputs>;
    getParcelSizeData?():Promise<{means:Float32Array;preview:PreviewIndex}>;
    getPreviewIndex?(): Promise<PreviewIndex | undefined>;
    getPreviewTile?(ref:PreviewTileRef,index:PreviewIndex,signal:AbortSignal):Promise<Uint8Array>;
    getNeighborhood(id: number, signal?: AbortSignal): Promise<NeighborhoodData>;
    getNeighborhoodChunkRefs?(bounds:ChunkBounds,signal:AbortSignal):Promise<NeighborhoodChunkRef[]|undefined>;
    getNeighborhoodChunk?(ref:NeighborhoodChunkRef,signal:AbortSignal):Promise<NeighborhoodChunk>;
    prioritizeNeighborhood?(id: number): void;
    streamParcels(neighborhood: number, ids: number[], signal: AbortSignal): AsyncIterable<ParcelRecord>;
    getParcelJobs?(ids: number[], signal?:AbortSignal): Promise<ParcelJob[]>;
    streamParcelJob?(job: ParcelJob, signal: AbortSignal): AsyncIterable<ParcelRecord>;
    close(): void;
}
